"""Generate the viewer's read-only bindings from the same checked artifacts used by deployment."""
import hashlib
import json
import sys
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments" / "m6"))
import run as fixture

READS = {
    "AgreementVault": "agreementId currentTerms termsHash state treasuryAcceptedRevision managerAcceptedRevision start scheduledEnd effectiveStop bandLower bandUpper positionId positionSalt positionLower positionUpper",
    "ServiceHook": "poolId qualification qualifyingSeconds projectedSeconds vault",
    "CompensationEscrow": "treasuryRecipient managerRecipient vault paymentToken fundedBudget earned claimed reserved claimable refunded refundable",
    "CustodyToken": "balanceOf decimals",
    "ComparisonRouter": "position",
}


# Hash verified creation artifacts in stable name order so the reader can identify its build.
@lru_cache
def buildId():
    names = sorted(set(READS) | {"PoolManager", "HookInstaller", "MockOpeningReferenceAdapter"})
    digest = hashlib.sha256()
    for name in names:
        artifact = fixture.artifact(name)  # Validates compiler settings and imported source hashes.
        digest.update(name.encode() + b'\0' + bytes.fromhex(artifact["bytecode"]["object"].removeprefix("0x")))
    return digest.hexdigest()


# Emit only the requested read-only ABI entries after checking every requested name.
def bindings():
    lines = ["// Generated by scripts/viewer/artifacts.py from verified Forge output.",
             f'export const buildId = "{buildId()}"']
    for name, requested in READS.items():
        abi = [entry for entry in fixture.artifact(name)["abi"] if entry["type"] == "function"
               and entry["name"] in requested.split() and entry["stateMutability"] in ("view", "pure")]
        assert {x["name"] for x in abi} == set(requested.split())
        lines.append(f"export const {name} = [")
        for entry in abi:
            lines.append("  " + json.dumps(entry, separators=(",", ":")) + ",")
        lines.append("] as const")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    target = ROOT / "viewer/src/contracts.ts"
    if sys.argv[1:] == ["--check"]:
        if target.read_text() != bindings():
            raise SystemExit("Re-export the ABI after compiling the pinned contracts.")
    else:
        target.write_text(bindings())
